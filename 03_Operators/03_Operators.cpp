#include <iostream>
using namespace std;

int main() {
	int a = 5, b = 4;
	cout << a + b << endl;
	cout << a - b << endl;
	cout << a * b << endl;
	cout << a / b << endl;
	cout << a % b << endl;
	cout << 3 % 7 << endl;
	cout << 8 % 9 << endl;
	cout << 10 % 9 << endl;

	int a = 2;
	cout << "a = " << a << endl;
	a = a + 1;
	cout << "a = " << a << endl;
	a++;
	cout << "a = " << a << endl;
	++a;
	cout << "a = " << a << endl;
}